// Builds migrations/0002_seed.sql from PokéAPI: every species (Gen I–IX) in
// Pokédex order. Regional forms go after the whole evolution line, grouped by
// region: Rattata, Raticate, Alolan Rattata, Alolan Raticate.
// Run with: node scripts/build-seed.mjs
import { writeFileSync } from 'node:fs'

const API = 'https://beta.pokeapi.co/graphql/v1beta'
const REGION = { alola: 'Alolan', galar: 'Galarian', hisui: 'Hisuian', paldea: 'Paldean' }
// Variants that are not separate regional forms (totems, cap Pikachu, Zen Mode,
// extra Tauros breeds). One entry per regional form is enough for a binder.
const SKIP = /-(totem|cap|zen)|tauros-paldea-(blaze|aqua)/

async function query(q) {
  const res = await fetch(API, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ query: q })
  })
  const json = await res.json()
  if (json.errors) throw new Error(JSON.stringify(json.errors))
  return json.data
}

const { pokemon_v2_pokemonspecies: species } = await query(`{
  pokemon_v2_pokemonspecies(order_by: {id: asc}) {
    id generation_id evolution_chain_id
    pokemon_v2_pokemonspeciesnames(where: {language_id: {_eq: 9}}) { name }
  }
}`)
const { pokemon_v2_pokemon: variants } = await query(`{
  pokemon_v2_pokemon(where: {name: {_regex: "-(alola|galar|hisui|paldea)"}}, order_by: {id: asc}) {
    name pokemon_species_id
  }
}`)

const REGION_ORDER = Object.keys(REGION)
const formsBySpecies = {}
for (const v of variants) {
  if (SKIP.test(v.name)) continue
  const region = v.name.match(/-(alola|galar|hisui|paldea)/)[1]
  ;(formsBySpecies[v.pokemon_species_id] ||= []).push(region)
}

// A "line" is a run of consecutive species in the same generation that share
// an evolution chain.
const lines = []
for (const s of species) {
  const prev = lines.at(-1)?.at(-1)
  if (prev && prev.evolution_chain_id === s.evolution_chain_id && prev.generation_id === s.generation_id) lines.at(-1).push(s)
  else lines.push([s])
}

const rows = []
const posByGen = {}
const englishName = (s) => {
  const name = s.pokemon_v2_pokemonspeciesnames[0]?.name
  if (!name) throw new Error(`Missing English name for species ${s.id}`)
  return name
}
for (const line of lines) {
  const gen = line[0].generation_id
  const add = (dex, name) => rows.push({ dex, name, gen, position: (posByGen[gen] = (posByGen[gen] || 0) + 1) })
  for (const s of line) add(s.id, englishName(s))
  for (const region of REGION_ORDER) {
    for (const s of line) {
      if ((formsBySpecies[s.id] || []).includes(region)) add(s.id, `${REGION[region]} ${englishName(s)}`)
    }
  }
}

const sql = (v) => `'${String(v).replace(/'/g, "''")}'`
const values = rows.map((r) => `(${r.dex}, ${sql(r.name)}, ${r.gen}, ${r.position})`)
const chunks = []
for (let i = 0; i < values.length; i += 100) {
  chunks.push(`INSERT INTO entries (dex, name, gen, position) VALUES\n${values.slice(i, i + 100).join(',\n')};`)
}
writeFileSync(new URL('../migrations/0002_seed.sql', import.meta.url), `-- Generated by scripts/build-seed.mjs from PokéAPI\n${chunks.join('\n\n')}\n`)

const perGen = Object.entries(posByGen).map(([g, n]) => `Gen ${g}: ${n}`).join(', ')
console.log(`Wrote ${rows.length} entries (${species.length} species). ${perGen}`)
